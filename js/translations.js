window.currentLanguage = localStorage.getItem('userLanguage') || 'ENGLISH';

function getTranslation(key) {
    const lang = window.currentLanguage;
    const lowerKey = key ? key.toLowerCase().replace('-', '') : '';

    // Check key normalization
    let baseKey = key;
    let suffix = '';
    let normalized = key;

    if (lowerKey.includes('disposal')) suffix = '_disposal';
    else if (lowerKey.includes('rule')) suffix = '_rule';

    if (lowerKey.includes('plastic')) baseKey = 'plastic';
    else if (lowerKey.includes('organic') || lowerKey.includes('wet')) baseKey = 'organic';
    else if (lowerKey.includes('glass')) baseKey = 'glass';
    else if (lowerKey.includes('metal')) baseKey = 'metal';
    else if (lowerKey.includes('ewaste') || lowerKey.includes('e-waste')) baseKey = 'ewaste';
    else if (lowerKey.includes('paper')) baseKey = 'paper';
    else if (lowerKey.includes('textile')) baseKey = 'textile';
    else if (lowerKey.includes('hazard')) baseKey = 'hazardous';
    else baseKey = key;

    if (suffix) {
        normalized = baseKey + suffix;
    } else {
        if (baseKey !== key) normalized = baseKey;
    }

    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) return TRANSLATIONS[lang][key];
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][normalized]) return TRANSLATIONS[lang][normalized];
    if (TRANSLATIONS['ENGLISH'][key]) return TRANSLATIONS['ENGLISH'][key];
    if (TRANSLATIONS['ENGLISH'][normalized]) return TRANSLATIONS['ENGLISH'][normalized];

    return key;
}

function setLanguage(lang) {
    window.currentLanguage = lang;
    localStorage.setItem('userLanguage', lang);
    applyTranslations();

    // Reload page if needed or just re-render components
    // dashboard.js calls applyTranslations.
    // Logic in analysis.js might need re-trigger if logic was purely JS based string concat.
    // For dashboard, we just reload window to be safe and easy? 
    // User said "Non-breaking". Reload is safe.
    location.reload();

    // Update Backend
    const email = localStorage.getItem('userEmail');
    if (email) {
        fetch('/api/auth/update-language', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ email, language: lang })
        }).catch(err => console.error("Language sync failed", err));
    }
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = getTranslation(key);

        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            if (el.hasAttribute('placeholder')) {
                el.placeholder = translation;
            }
        } else {
            el.innerHTML = translation;
        }
    });
}

